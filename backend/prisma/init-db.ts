/**
 * init-db.ts
 * Starts an embedded PostgreSQL instance for local development.
 * Run once: npm run db:init
 */

// eslint-disable-next-line @typescript-eslint/no-var-requires
const EmbeddedPostgres = require('embedded-postgres').default;
import * as path from 'path';
import * as fs from 'fs';

const DATA_DIR = path.join(__dirname, '..', '.postgres-data');
const PG_PORT = 5433;
const DB_NAME = 'nexus_academic';
const DB_USER = 'nexus_user';
const DB_PASS = 'nexus_pass123';

async function main() {
  console.log('🚀 Initializing embedded PostgreSQL...');

  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }

  const pg = new EmbeddedPostgres({
    databaseDir: DATA_DIR,
    user: DB_USER,
    password: DB_PASS,
    port: PG_PORT,
    persistent: true,
  });

  await pg.initialise();
  await pg.start();
  console.log(`✅ PostgreSQL started on port ${PG_PORT}`);

  const client = pg.getPgClient();
  await client.connect();

  try {
    await client.query(`CREATE DATABASE ${DB_NAME}`);
    console.log(`✅ Database "${DB_NAME}" created`);
  } catch (e: any) {
    if (e.code === '42P04') {
      console.log(`ℹ️  Database "${DB_NAME}" already exists`);
    } else {
      console.error('DB create error:', e.message);
    }
  }

  await client.end();
  await pg.stop();
  console.log('✅ PostgreSQL stopped (will restart with app)');

  // Write .env file
  const envPath = path.join(__dirname, '..', '.env');
  const envContent = `# Auto-generated by db:init — do not edit manually
DATABASE_URL="postgresql://${DB_USER}:${DB_PASS}@localhost:${PG_PORT}/${DB_NAME}"
JWT_SECRET="nexus-jwt-secret-change-in-production-2024"
JWT_REFRESH_SECRET="nexus-jwt-refresh-secret-change-in-production-2024"
JWT_EXPIRES_IN="7d"
JWT_REFRESH_EXPIRES_IN="30d"
PORT=3001
FRONTEND_URL="http://localhost:5500"
UPLOAD_DIR="./uploads"
MAX_FILE_SIZE=10485760
EMBEDDED_PG_PORT=${PG_PORT}
EMBEDDED_PG_USER="${DB_USER}"
EMBEDDED_PG_PASS="${DB_PASS}"
EMBEDDED_PG_DATA_DIR="${DATA_DIR}"
NODE_ENV="development"
`;

  fs.writeFileSync(envPath, envContent);
  console.log('✅ .env file written');
  console.log('\n🎉 DB initialization complete!');
  console.log('   Next: npm run db:push && npm run db:seed && npm run dev\n');

  process.exit(0);
}

main().catch((e) => {
  console.error('❌ DB init failed:', e);
  process.exit(1);
});
